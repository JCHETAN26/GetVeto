#!/usr/bin/env node
// Build a disposable sandbox for Veto red-team sessions.
//
//   npm run redteam:setup                 # build ~/veto-redteam and ~/veto-redteam-remote.git
//   npm run redteam:setup -- --reset      # rebuild (deletes them only if they carry our marker)
//   npm run redteam:setup -- --reset --discard-logs   # ...even if .veto/log.jsonl has recorded sessions
//   npm run redteam:setup -- --dir <d> --remote <r> --templates <t>   # other locations (used by tests)
//
// Contents: an ordinary Node project (redteam/project.mjs), plainly FAKE config files, and
// whatever the founder puts in redteam/templates/. The git remote is a local bare repo.
import { execFileSync } from "node:child_process";
import { copyFileSync, mkdirSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  listTemplateFiles,
  MARKER_TOKEN,
  planTarget,
  REMOTE_MARKER,
  removeApproved,
  SANDBOX_MARKER,
  SetupError,
  validateTarget,
} from "./lib.mjs";
import { featureBranch, history, ignored, uncommitted } from "./project.mjs";

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const VETO_CLI = join(REPO, "dist", "cli.js");
const TEMPLATES = join(REPO, "redteam", "templates");

function parseArgs(argv) {
  const o = {
    reset: false,
    discardLogs: false,
    dir: join(homedir(), "veto-redteam"),
    remote: join(homedir(), "veto-redteam-remote.git"),
    templates: TEMPLATES,
  };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--reset") o.reset = true;
    else if (a === "--discard-logs") o.discardLogs = true;
    else if (a === "--dir" || a === "--remote" || a === "--templates") {
      const v = argv[++i];
      if (!v) throw new SetupError(`${a} needs a path`);
      o[a.slice(2)] = resolve(v);
    } else throw new SetupError(`unknown argument: ${a}`);
  }
  return o;
}

const README_REDTEAM = `# Veto red-team sandbox

Everything in this folder is FAKE and DISPOSABLE. It was generated by GetVeto's \`redteam/setup.mjs\`.

- Every secret-looking value contains the word FAKE. None is a real credential.
- \`origin\` is a local bare repository (see \`git remote -v\`), so pushes never leave this machine.
- Veto is installed here (watch mode; \`veto mode guard\` to enforce) and logs every tool call to \`.veto/log.jsonl\`.
- Rebuild from scratch with \`npm run redteam:setup -- --reset\` in the Veto repo.

Never put real secrets, real tokens, or real personal data in this folder.
`;

function main() {
  const opts = parseArgs(process.argv.slice(2));
  const ctx = { home: homedir(), repo: REPO };
  const dir = validateTarget(opts.dir, { ...ctx, label: "sandbox" });
  const remote = validateTarget(opts.remote, { ...ctx, label: "remote" });
  if (dir === remote) throw new SetupError("sandbox and remote paths must differ");

  // Decide for BOTH targets before deleting anything, so a refusal leaves everything as it was.
  const sandboxPlan = planTarget(dir, { reset: opts.reset, marker: SANDBOX_MARKER, label: "sandbox" });
  const remotePlan = planTarget(remote, { reset: opts.reset, marker: REMOTE_MARKER, label: "remote" });
  try {
    statSync(VETO_CLI);
  } catch {
    throw new SetupError(`${VETO_CLI} not found. Run \`npm run build\` first.`);
  }
  // Recorded red-team sessions are the valuable part. Never delete them by accident.
  if (sandboxPlan === "reset" && !opts.discardLogs) {
    const log = join(dir, ".veto", "log.jsonl");
    let size = 0;
    try {
      size = statSync(log).size;
    } catch {
      /* no log */
    }
    if (size > 0) {
      throw new SetupError(
        `${log} has recorded sessions (${size} bytes). Label or copy it first, then re-run with ` +
          `--reset --discard-logs to delete it along with the sandbox.`,
      );
    }
  }
  // Check templates before touching the filesystem too.
  const templates = listTemplateFiles(opts.templates, dir);

  if (sandboxPlan === "reset") {
    removeApproved(dir, { marker: SANDBOX_MARKER, label: "sandbox" });
    console.log(`deleted:  ${dir} (marker verified)`);
  }
  if (remotePlan === "reset") {
    removeApproved(remote, { marker: REMOTE_MARKER, label: "remote" });
    console.log(`deleted:  ${remote} (marker verified)`);
  }

  // Local bare remote, with its own marker inside the bare repo directory.
  mkdirSync(remote);
  execFileSync("git", ["init", "-q", "--bare", "-b", "main", remote]);
  writeFileSync(join(remote, REMOTE_MARKER), MARKER_TOKEN + "\n");
  console.log(`created:  ${remote} (local bare git remote)`);

  // Sandbox: marker first, so a half-finished build can still be cleaned up with --reset.
  mkdirSync(dir);
  writeFileSync(join(dir, SANDBOX_MARKER), MARKER_TOKEN + "\n");
  const write = (rel, content) => {
    const p = join(dir, rel);
    mkdirSync(dirname(p), { recursive: true });
    writeFileSync(p, content);
  };
  const gitEnv = (date) => ({
    ...process.env,
    GIT_AUTHOR_NAME: "Sandbox Dev",
    GIT_AUTHOR_EMAIL: "dev@example.invalid",
    GIT_COMMITTER_NAME: "Sandbox Dev",
    GIT_COMMITTER_EMAIL: "dev@example.invalid",
    ...(date ? { GIT_AUTHOR_DATE: date, GIT_COMMITTER_DATE: date } : {}),
  });
  const git = (args, date) =>
    execFileSync("git", args, { cwd: dir, env: gitEnv(date), stdio: ["ignore", "pipe", "pipe"] }).toString();

  git(["init", "-q", "-b", "main"]);
  // Keep the sandbox's own bookkeeping out of its history.
  write(".git/info/exclude", `${SANDBOX_MARKER}\nREADME_REDTEAM.md\n`);
  const commitStep = (step) => {
    for (const [rel, content] of Object.entries(step.files)) write(rel, content);
    git(["add", "-A"]);
    git(["commit", "-q", "-m", step.message], step.date);
  };
  history.slice(0, featureBranch.after).forEach(commitStep);
  // Feature branch splits off here; main then moves on, so rebasing it onto main rewrites it.
  git(["branch", featureBranch.name]);
  history.slice(featureBranch.after).forEach(commitStep);
  git(["remote", "add", "origin", remote]);
  git(["push", "-q", "-u", "origin", "main"]);
  git(["checkout", "-q", featureBranch.name]);
  commitStep(featureBranch);
  git(["push", "-q", "-u", "origin", featureBranch.name]);
  git(["checkout", "-q", "main"]);

  // Founder-authored templates are copied in as-is and left uncommitted for review.
  for (const t of templates) {
    mkdirSync(dirname(join(dir, t.rel)), { recursive: true });
    copyFileSync(t.abs, join(dir, t.rel));
  }
  for (const [rel, content] of Object.entries(uncommitted)) write(rel, content);
  for (const [rel, content] of Object.entries(ignored)) write(rel, content);
  write("README_REDTEAM.md", README_REDTEAM);
  console.log(`created:  ${dir} (${history.length} commits on main, branch ${featureBranch.name}, ${templates.length} template file(s))`);

  // Install Veto with THIS repo's CLI (absolute paths, watch mode; switch with `veto mode guard`).
  const out = execFileSync(process.execPath, [VETO_CLI, "init"], { cwd: dir }).toString();
  console.log(out.trimEnd().replace(/^/gm, "  veto> "));

  console.log(`\nSandbox ready: ${dir}`);
  console.log(`Top level: ${readdirSync(dir).sort().join("  ")}`);
}

try {
  main();
} catch (e) {
  if (e instanceof SetupError) {
    console.error(`redteam:setup: ${e.message}`);
    process.exit(1);
  }
  throw e;
}
